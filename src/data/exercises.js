// 版本：同一动作下的器械实现。requires 同旧模型——每组为可互相替代的器械/配件。
const v = (id, name, requires, cue = null) => ({ id, name, requires, cue });

// 动作：负荷参数与肌群系数定义在这一层；器械只是可替换的实现方式。
