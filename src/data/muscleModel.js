const singleDumbbell = new Set(['db-row', 'db-preacher-curl', 'wrist-curl', 'goblet-squat', 'db-calf']);
const unilateral = new Set(['db-row', 'cable-row', 'cable-lateral', 'cable-reverse-fly', 'db-preacher-curl', 'wrist-curl', 'split-squat', 'cable-kickback', 'machine-kickback', 'db-calf']);
export function enrichVariant(movement, variant) {
  const equipment = variant.requires.flat();
  const dumbbell = equipment.includes('dumbbell');
  const cable = equipment.some((id) => ['cable', 'cableCrossover', 'latPulldown', 'seatedRow'].includes(id));
  const free = dumbbell || equipment.includes('barbell') || equipment.includes('ezBar');
  const specifics = override[variant.id] ?? {};
  return { ...variant, parameters: {
    repRange: movement.repRange, rest: movement.rest, rir: movement.rir, increment: movement.increment,
    primary: movement.primary, secondary: movement.secondary, stabilizers: movement.stabilizers,
    loadMode: movement.loadMode ?? 'external', loadLabel: movement.loadLabel ?? (dumbbell ? '单只重量 kg' : cable ? '配重刻度 kg' : free ? '总重量 kg' : '器械负重 kg'),
    resistance: cable ? '滑轮阻力' : free ? '自由重量' : '器械阻力',
    setup: variant.name, ...specifics,
    regions: { ...(MOVEMENT_REGIONS[movement.id] ?? movement.regions), ...specifics.regions },
    loadMultiplier: movement.loadMultiplier ?? (dumbbell && !singleDumbbell.has(variant.id) ? 2 : 1),
    loadBasis: 'recorded',
    laterality: unilateral.has(variant.id) ? 'unilateral' : 'bilateral',
    capacityLabel: unilateral.has(variant.id) ? '单侧容量' : '容量',
  } };
}

export function resolveMovement(movement, variantId) {
  if (!movement) return movement;
  const variant = movement.variants?.find((item) => item.id === variantId);
  const parameters = variant?.parameters;
  if (!parameters) return { ...movement, variantId, regions: movement.regions ?? {}, loadMode: movement.loadMode ?? 'external', loadLabel: movement.loadLabel ?? '记录重量 kg', loadMultiplier: movement.loadMultiplier ?? 1 };
  return { ...movement, ...parameters, variantId, regions: { ...parameters.regions }, variantProfile: parameters };
}
